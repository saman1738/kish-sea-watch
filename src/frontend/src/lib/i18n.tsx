const dictionaries: Record<Lang, Record<TranslationKey, string>> = { en, fa };

export type Translate = (key: TranslationKey) => string;

export interface I18nValue {
  lang: Lang;
  dir: "ltr" | "rtl";
  isRtl: boolean;
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
  t: Translate;
  /** Pick the localized field from a bilingual pair. */
  pick: (enText: string, faText: string) => string;
  /** Format a number with locale-aware digits. */
  num: (value: number, digits?: number) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

function readInitialLang(): Lang {
  if (typeof window === "undefined") return "en";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === "fa" ? "fa" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readInitialLang);
  const dir = lang === "fa" ? "rtl" : "ltr";

  useEffect(() => {
    const root = document.documentElement;
    root.lang = lang;
    root.dir = dir;
    window.localStorage.setItem(STORAGE_KEY, lang);
  }, [lang, dir]);

  const setLang = useCallback((next: Lang) => setLangState(next), []);
  const toggleLang = useCallback(
    () => setLangState((current) => (current === "en" ? "fa" : "en")),
    [],
  );

  const value = useMemo<I18nValue>(() => {
    const dict = dictionaries[lang];
    const locale = lang === "fa" ? "fa-IR" : "en-US";
    return {
      lang,
      dir,
      isRtl: lang === "fa",
      setLang,
      toggleLang,
      t: (key) => dict[key] ?? en[key],
      pick: (enText, faText) =>
        lang === "fa" ? faText || enText : enText || faText,
      num: (n, digits = 0) =>
        new Intl.NumberFormat(locale, {
          minimumFractionDigits: digits,
          maximumFractionDigits: digits,
        }).format(n),
    };
  }, [lang, dir, setLang, toggleLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
